import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = async (path) =>
  JSON.parse(await readFile(new URL(path, root), 'utf8'));
const source = Object.assign(
  {},
  ...(await Promise.all(
    ['colours', 'core', 'semantic', 'typeface'].map((name) =>
      read(`tokens/${name}.json`),
    ),
  )),
);
Object.assign(source, await read('packages/flutter/tokens/typography.json'));
const name = (parts) =>
  parts.join('-').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const resolve = (value, seen = []) => {
  if (typeof value !== 'string' || !value.startsWith('{')) return value;
  const path = value.slice(1, -1);
  if (seen.includes(path)) throw new Error(`Circular token: ${path}`);
  const token = path.split('.').reduce((node, key) => node?.[key], source);
  if (!token) throw new Error(`Missing token: ${path}`);
  return resolve(token.$value, [...seen, path]);
};
const declarations = [];
function walk(node, path = []) {
  if ('$value' in node) {
    const value = resolve(node.$value);
    let expression;
    switch (node.$type) {
      case 'color':
        if (!/^#[0-9a-f]{6}$/i.test(value))
          throw new Error(`Unsupported color: ${value}`);
        expression = `Color(0xFF${value.slice(1).toUpperCase()})`;
        break;
      case 'dimension':
        if (value.unit !== 'px') throw new Error('Expected px');
        expression = Number(value.value).toFixed(2);
        break;
      case 'fontWeight':
        expression = `FontWeight.w${value}`;
        break;
      case 'fontFamily':
        expression = JSON.stringify(value[0]);
        break;
      default:
        throw new Error(`Unsupported type: ${node.$type}`);
    }
    declarations.push(`  static const ${name(path)} = ${expression};`);
    return;
  }
  for (const [key, value] of Object.entries(node)) {
    if (!key.startsWith('$')) walk(value, [...path, key]);
  }
}
walk(source);
const destination = new URL('packages/flutter/', root);
await mkdir(new URL('lib/src/generated/', destination), { recursive: true });
await writeFile(
  new URL('lib/src/generated/kofa_tokens.dart', destination),
  `// GENERATED by npm run tokens:build. Do not edit.\nimport 'package:flutter/material.dart';\n\nabstract final class KofaTokens {\n${declarations.join('\n')}\n}\n`,
);
await mkdir(new URL('assets/fonts/', destination), { recursive: true });
for (const weight of ['Regular', 'Medium']) {
  const file = `TWKEverett-${weight}-web.ttf`;
  await copyFile(
    new URL(`font/${file}`, root),
    new URL(`assets/fonts/${file}`, destination),
  );
}
console.log(
  `Flutter: generated ${declarations.length} tokens and synchronized fonts.`,
);
